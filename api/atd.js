const 구분목록 = ['질병', '취업', '경조사', '국가소집', '교통', '개인부주의'];

// ─── 핸들러 ──────────────────────────────────────────────────
export default function handler(req, res) {
  const body = req.body || {};

  // 버튼 클릭 (JSON body에 context 포함)
  if (body.context) return res.status(200).json({ update: { message: '', props: { attachments: route(body.context) } } });

  // 슬래시 커맨드 최초 실행
  return res.status(200).json({ response_type: 'ephemeral', username: '출결도우미', attachments: 시작화면() });
}

function route(ctx) {
  switch (ctx.step) {
    case 'cat': return 사유선택(ctx.cat);
    case 'rule': return 규칙처리(ctx.id);
    case 'branch': return 분기결과(ctx.id, Number(ctx.bi));
    case 'job1': return ctx.v === 'no' ? 최종(RULES[ctx.id], '공가') : 취업질문2(ctx.id);
    case 'job2': return 최종(RULES[ctx.id], ctx.v === 'no' ? '사유출결' : '임의출결', ctx.v === 'no'
      ? '취업 공가 3회를 모두 사용하셨으므로 **사유결석**으로 신청합니다.'
      : '취업 공가 3회 + 사유결석 2회를 모두 사용하셨으므로 **임의결석**으로 신청합니다.');
    default: return 시작화면();
  }
}

// ─── 화면 ────────────────────────────────────────────────────
function 시작화면() {
  return card('### 🚨 출결 판정 도우미\n어떤 사유인가요?',
    구분목록.map((c) => btn(c, { step: 'cat', cat: c })));
}

function 사유선택(cat) {
  const items = Object.entries(RULES).filter(([, r]) => r.구분 === cat);
  return card(`**${cat}** — 해당하는 항목을 선택하세요.`,
    items.map(([id, r]) => btn(r.사유, { step: 'rule', id })).concat(홈버튼()));
}

function 규칙처리(id) {
  const r = RULES[id];
  if (r.유형 === '분기') {
    return card(`**${r.사유}**\n${r.질문}`,
      r.분기.map((b, i) => btn(b.라벨, { step: 'branch', id, bi: String(i) })).concat(홈버튼()));
  }
  if (r.취업공가) {
    return card(`**${r.사유}**\n이번 달 취업 관련 공가를 3회 모두 사용하셨나요?\n_(면접·인적성·코딩테스트·채용검진·자격증시험 합산, 월 3회 한도)_`,
      [btn('아직 남아있어요', { step: 'job1', id, v: 'no' }), btn('3회 다 썼어요', { step: 'job1', id, v: 'yes' })].concat(홈버튼()));
  }
  return 최종(r, r.유형);
}

function 취업질문2(id) {
  return card(`**${RULES[id].사유}**\n사유결석도 2회 모두 사용하셨나요?`,
    [btn('아니요', { step: 'job2', id, v: 'no' }), btn('네, 2회 다 썼어요', { step: 'job2', id, v: 'yes' })].concat(홈버튼()));
}

function 분기결과(id, i) {
  const r = RULES[id], b = r.분기[i];
  return 최종({ ...r, 증빙: b.증빙, 사유: `${r.사유} — ${b.조건}` }, b.유형);
}

function 최종(r, 유형, 안내) {
  const L = [`### ${표시[유형]}`, `**${r.사유}** · ${r.구분}`, ''];
  if (안내) L.push(안내, '');
  L.push(`📎 증빙: ${r.증빙}`);
  if (r.시점) L.push(`📅 신청 가능 시점: ${r.시점}`);
  if (r.비고 && r.비고.length) { L.push('', '📌 참고'); r.비고.forEach((b) => L.push(`- ${b}`)); }
  L.push(공통안내);
  return card(L.join('\n'), 홈버튼());
}

// ─── 유틸 ────────────────────────────────────────────────────
function card(text, actions) {
  // 버튼은 attachment당 4개씩 나눠 담습니다 (한 줄에 몰리면 잘려 보임)
  const chunks = [];
  for (let i = 0; i < actions.length; i += 4) chunks.push(actions.slice(i, i + 4));
  return chunks.length
    ? chunks.map((acts, i) => ({ text: i === 0 ? text : '', actions: acts }))
    : [{ text }];
}

function btn(name, context) {
  return {
    id: `${context.step}_${context.id || context.cat || ''}_${context.v || context.bi || ''}_${name}`.replace(/\s/g, ''),
    name,
    integration: { url: BASE_URL, context },
  };
}

function 홈버튼() {
  return [{ id: 'home', name: '↩ 처음으로', integration: { url: BASE_URL, context: { step: 'home' } } }];
}
